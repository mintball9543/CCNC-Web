/* ───────────────────────── 공통 타입 ───────────────────────── */

export type InfoCell =
  | string
  | {
      text: string;
      colSpan?: number;
      rowSpan?: number;
      /** 머리글 셀 여부 (생략하면 rowHeaderCols 기준) */
      th?: boolean;
      align?: "left" | "right";
      emphasis?: boolean;
    };

export interface InfoTableData {
  caption: string;
  unit?: string;
  head: InfoCell[][];
  rows: InfoCell[][];
  /** 앞에서부터 몇 열을 행 머리글로 볼지 (기본 1) */
  rowHeaderCols?: number;
  notes?: string[];
  source?: string;
  /** Tailwind 최소 너비 클래스 */
  minWidth?: string;
}

export interface StaticChart {
  title: string;
  description?: string;
  unit: string;
  chartType: ChartType;
  categoryLabel: string;
  series: string[];
  rows: { label: string; values: (number | null)[] }[];
  source?: string;
}

